
CREATE TABLE orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
    order_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    order_status VARCHAR(30) NOT NULL DEFAULT 'Pending Payment',
    CONSTRAINT chk_order_status CHECK (
        order_status IN (
            'Pending Payment', 'Awaiting Fulfilment',
            'Stock Issue', 'Dispatched', 'Delivered', 'Cancelled'
        )
    )
);

CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id),
    product_id INTEGER NOT NULL REFERENCES products(product_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_at_order DECIMAL(10,2) NOT NULL
        CHECK (unit_price_at_order >= 0)
);

CREATE TABLE payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id),
    amount DECIMAL(10,2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(30),
    payment_status VARCHAR(20) NOT NULL,
    attempted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_payment_status CHECK (
        payment_status IN ('Pending', 'Processing', 'Successful', 'Failed')
    )
);

CREATE TABLE inventory (
    inventory_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL UNIQUE REFERENCES products(product_id),
    quantity_on_hand INTEGER NOT NULL CHECK (quantity_on_hand >= 0),
    quantity_allocated INTEGER NOT NULL DEFAULT 0
        CHECK (quantity_allocated >= 0),
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_inventory_allocation CHECK (
        quantity_allocated <= quantity_on_hand
    )
);

CREATE TABLE deliveries (
    delivery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL UNIQUE REFERENCES orders(order_id),
    delivery_address VARCHAR(255) NOT NULL,
    delivery_status VARCHAR(30) NOT NULL DEFAULT 'Awaiting Dispatch',
    dispatched_at TIMESTAMP,
    delivered_at TIMESTAMP,
    CONSTRAINT chk_delivery_status CHECK (
        delivery_status IN ('Awaiting Dispatch', 'In Transit', 'Delivered')
    )
);
